    private void AgregarMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_AgregarMouseClicked
        // TODO add your handling code here:
        try {
            String codigo = Input.getText();
            Cliente cliente = banco.seleccionarClientePorID(codigo);
            if (!propietariosA.isEmpty()) {
                for (int i = 0; i < propietariosA.size(); i++) {
                    if (cliente == propietariosA.get(i)) {
                        throw new Exception("Ese usuario ya esta como propietario");
                    }
                }
            }
            propietariosA.add(cliente);
            
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
        cargarPropietarios();
    }//GEN-LAST:event_AgregarMouseClicked

    private void QuitarMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_QuitarMouseClicked
        // TODO add your handling code here:
        try {
            boolean hecho = false;
            String codigo = Input.getText();
            Cliente cliente = banco.seleccionarClientePorID(codigo);
            if (propietariosA.isEmpty()) {
                throw new Exception("No hay propietarios");
            }
            for (int i = 0; i < propietariosA.size(); i++) {
                if (cliente == propietariosA.get(i)) {
                    propietariosA.remove(i);
                    hecho = true;
                }
            }
            if (!hecho) {
                throw new Exception("Cliente no encontrado en propietarios");
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
        cargarPropietarios();
    }//GEN-LAST:event_QuitarMouseClicked

    private void CrearMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_CrearMouseClicked
        // TODO add your handling code here:
        try {
            if(propietariosA.isEmpty()) {
                throw new Exception("La lista de propietarios esta vacia");
            }
            if(empleado != null) {
                banco.crearCuenta(empleado, propietariosA);
            } else if(administrador != null) {
                banco.crearCuenta(administrador, propietariosA);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_CrearMouseClicked

    private void VolverMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_VolverMouseClicked
        // TODO add your handling code here:
        if(empleado != null) {
            MenuEmpleado ME = new MenuEmpleado(banco, empleado);
            ME.setLocationRelativeTo(this);
            ME.setVisible(true);
            this.dispose();
        } else if (administrador != null) {
            MenuAdministrador MA = new MenuAdministrador(banco, administrador);
            MA.setLocationRelativeTo(this);
            MA.setVisible(true);
            this.dispose();
        }
    }//GEN-LAST:event_VolverMouseClicked

