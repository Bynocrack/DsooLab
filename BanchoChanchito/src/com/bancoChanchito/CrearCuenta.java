    private void cargarClientes() {
        DefaultListModel<String> clientes = new DefaultListModel<>();
        ArrayList<String> datos = banco.listarClientes();
        
        for (int i = 0; i < datos.size(); i++) {
            clientes.addElement(datos.get(i));
        }
        
        ListaClientes.setModel(clientes);
    }
    private void cargarPropietarios(){
        DefaultListModel<String> propietarios = new DefaultListModel<>();
        
        for (int i = 0; i < propietariosA.size(); i++) {
            propietarios.addElement(propietariosA.get(i).getIdCliente() + " - " + propietariosA.get(i).getNombre());
        }
        ListaPropietarios.setModel(propietarios);
    }
