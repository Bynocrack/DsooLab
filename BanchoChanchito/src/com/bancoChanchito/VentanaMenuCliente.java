    private void btnConsultarCuentasActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarCuentasActionPerformed
         if (cliente.getCuentas().isEmpty()) {
            JOptionPane.showMessageDialog(
                this,
                "No tiene cuentas registradas",
                "Sin cuentas",
                JOptionPane.INFORMATION_MESSAGE
            );
            return;
        }
        
        StringBuilder resumen = new StringBuilder();
        resumen.append("=== CUENTAS DEL CLIENTE ").append(cliente.getNombre()).append(" ===\n\n");
        
        for (modelos.Cuenta c : cliente.getCuentas()) {
            resumen.append("Número: ").append(c.getNumero()).append("\n");
            resumen.append("Tipo: ").append(c.getTipo()).append("\n");
            resumen.append("Saldo: S/ ").append(String.format("%.2f", c.getSaldo())).append("\n");
            resumen.append("─────────────────────────\n");
        }
        
        JTextArea textArea = new JTextArea(resumen.toString());
        textArea.setEditable(false);
        textArea.setFont(new Font("Monospaced", Font.PLAIN, 12));
        
        JScrollPane scrollPane = new JScrollPane(textArea);
        scrollPane.setPreferredSize(new Dimension(400, 300));
        
        JOptionPane.showMessageDialog(
            this,
            scrollPane,
            "Resumen de Cuentas",
            JOptionPane.INFORMATION_MESSAGE
        );       // TODO add your handling code here:
    }//GEN-LAST:event_btnConsultarCuentasActionPerformed

