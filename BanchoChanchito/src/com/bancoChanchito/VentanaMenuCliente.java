    private void btnVerMovimientosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnVerMovimientosActionPerformed
        if (cliente.getCuentas().isEmpty()) {
            JOptionPane.showMessageDialog(
                this,
                "No tiene cuentas registradas",
                "Sin cuentas",
                JOptionPane.INFORMATION_MESSAGE
            );
            return;
        }
        
        // Seleccionar cuenta
        String[] opciones = cliente.getCuentas().stream()
            .map(c -> c.getNumero() + " - S/ " + String.format("%.2f", c.getSaldo()))
            .toArray(String[]::new);
        
        String seleccion = (String) JOptionPane.showInputDialog(
            this,
            "Seleccione una cuenta:",
            "Ver Movimientos",
            JOptionPane.QUESTION_MESSAGE,
            null,
            opciones,
            opciones[0]
        );
        
        if (seleccion != null) {
            String numCuenta = seleccion.split(" - ")[0];
            modelos.Cuenta cuenta = cliente.getCuentas().stream()
                .filter(c -> c.getNumero().equals(numCuenta))
                .findFirst()
                .orElse(null);
            
            if (cuenta != null) {
                mostrarMovimientosCuenta(cuenta);
            }
        }                                                
        // TODO add your handling code here:
    }//GEN-LAST:event_btnVerMovimientosActionPerformed

