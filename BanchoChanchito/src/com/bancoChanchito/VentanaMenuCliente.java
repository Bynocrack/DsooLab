    private void mostrarMovimientosCuenta(modelos.Cuenta cuenta) {
        if (cuenta.getMovimientos().isEmpty()) {
            JOptionPane.showMessageDialog(
                this,
                "La cuenta no tiene movimientos registrados",
                "Sin movimientos",
                JOptionPane.INFORMATION_MESSAGE
            );
            return;
        }
        
        StringBuilder movimientos = new StringBuilder();
        movimientos.append("=== MOVIMIENTOS DE CUENTA ").append(cuenta.getNumero()).append(" ===\n\n");
        
        for (modelos.Transaccion t : cuenta.getMovimientos()) {
            movimientos.append("ID: ").append(t.getId()).append("\n");
            movimientos.append("Fecha: ").append(t.getFechaHora()).append("\n");
            movimientos.append("Monto: S/ ").append(String.format("%.2f", t.getMonto())).append("\n");
            movimientos.append("Tipo: ").append(t instanceof modelos.Deposito ? "DEPÓSITO" : "RETIRO").append("\n");
            movimientos.append("─────────────────────────\n");
        }
        
        JTextArea textArea = new JTextArea(movimientos.toString());
        textArea.setEditable(false);
        textArea.setFont(new Font("Monospaced", Font.PLAIN, 12));
        
        JScrollPane scrollPane = new JScrollPane(textArea);
        scrollPane.setPreferredSize(new Dimension(450, 350));
        
        JOptionPane.showMessageDialog(
            this,
            scrollPane,
            "Movimientos de Cuenta",
            JOptionPane.INFORMATION_MESSAGE
        );
    }            
